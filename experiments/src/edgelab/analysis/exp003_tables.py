"""EXP-003 results tables (markdown) from saved per-frame scores + results.jsonl run ids.

    uv run --extra pose python -m edgelab.analysis.exp003_tables --root ~/thesis-data/exp003 --variant paper --out <md>
"""

import argparse
import json
from pathlib import Path

from edgelab.analysis.exp003 import GATES, cross_fit, diff, load_scores, summarize

LEVELS = ("L0", "L1", "L2", "L3", "L4", "L2-nonoise")
ENHANCERS = ("E0", "E1", "E2", "E3")


def pct(x: float) -> str:
    return f"{x * 100:.2f}"


def fmt_diff(d: dict) -> str:
    return f"{d['diff'] * 100:+.2f} [{d['ci'][0] * 100:+.2f}, {d['ci'][1] * 100:+.2f}]"


def run_ids(root: Path, variant: str) -> dict[tuple, str]:
    rows = [json.loads(line) for line in (root / "results.jsonl").read_text().splitlines() if line.strip()]
    return {(r["cache"], r["c"]): r.get("run_id", "no-run") for r in rows if r["variant"] == variant}


def holm(p_like: list[float]) -> list[float]:
    """Holm step-down on one-sided bootstrap p-values (smallest first)."""
    order = sorted(range(len(p_like)), key=lambda i: p_like[i])
    adjusted, running = [0.0] * len(p_like), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(p_like) - rank) * p_like[i]))
        adjusted[i] = running
    return adjusted


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--variant", default="paper")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    ids = run_ids(args.root, args.variant)
    load = lambda cache, c=0.25: load_scores(args.root, cache, c, args.variant)  # noqa: E731
    out = [f"# EXP-003 tables — variant `{args.variant}` (generated by edgelab.analysis.exp003_tables)", ""]

    out += ["## T1. AUC by light level × enhancement (c 0.25); Δ vs E0 at the same level, paired 95% CI", "",
            "| Level | E | AUC [95% CI] | Δ vs E0 | anomalous coverage* | run id |", "|---|---|---|---|---|---|"]
    best_enh = {}
    for level in LEVELS:
        base = load(f"{level}_E0")
        for enh in ENHANCERS:
            s = load(f"{level}_{enh}")
            if s is None:
                continue
            summ = summarize(s)
            d = diff(base, s) if enh != "E0" else None
            if d and (level not in best_enh or d["diff"] > best_enh[level][1]["diff"]):
                best_enh[level] = (enh, d)
            covered = sum(c[l == 1].sum() for c, l in zip(s.covered, s.labels)) / sum((l == 1).sum() for l in s.labels)
            out.append(f"| {level} | {enh} | {pct(summ['auc'])} [{pct(summ['ci'][0])}, {pct(summ['ci'][1])}] | "
                       f"{fmt_diff(d) if d else '—'} | {covered:.3f} | `{ids.get((f'{level}_{enh}', 0.25), '?')[:8]}` |")
    out += ["", "*fraction of anomalous frames with ≥ 1 scored person.", ""]

    out += ["## T2. Gate: cross-fitted c vs default, per (level, E) — H3, H6", "",
            "| Level | E | default | G-xfit | Δ (xfit − default) | c chosen (fold A, B) |", "|---|---|---|---|---|---|"]
    xfits = {}
    for level in LEVELS:
        for enh in ENHANCERS:
            by_gate = {c: s for c in GATES if (s := load(f"{level}_{enh}", c)) is not None}
            if len(by_gate) < len(GATES):
                continue
            xfit, chosen = cross_fit(by_gate)
            xfits[(level, enh)] = xfit
            d = diff(by_gate[0.25], xfit)
            out.append(f"| {level} | {enh} | {pct(summarize(by_gate[0.25])['auc'])} | {pct(summarize(xfit)['auc'])} | "
                       f"{fmt_diff(d)} | {chosen['fit_on_A']}, {chosen['fit_on_B']} |")
    out.append("")

    out += ["## T3. H4 — gate re-calibration vs best enhancement (both vs E0 c 0.25); Holm over L2, L3", "",
            "| Level | Δ G-xfit (E0) | best E | Δ best E | Δ (G-xfit − best E) | one-sided p (G ≥ E fails) | Holm |",
            "|---|---|---|---|---|---|---|"]
    rows, ps = [], []
    for level in ("L2", "L3"):
        base, xfit = load(f"{level}_E0"), xfits[(level, "E0")]
        enh, d_enh = best_enh[level]
        d_g, d_ge = diff(base, xfit), diff(load(f"{level}_{enh}"), xfit)
        p = d_ge["p_le_zero"]
        rows.append((level, d_g, enh, d_enh, d_ge, p))
        ps.append(p)
    for (level, d_g, enh, d_enh, d_ge, p), p_holm in zip(rows, holm(ps)):
        out.append(f"| {level} | {fmt_diff(d_g)} | {enh} | {fmt_diff(d_enh)} | {fmt_diff(d_ge)} | {p:.3f} | {p_holm:.3f} |")
    out.append("")

    out += ["## T4. Addendum A — resolution (E0, c 0.25); Δ vs 640 at the same level", "",
            "| Level | imgsz | AUC [95% CI] | Δ vs 640 | Δ vs best enhancement at 640 | run id |", "|---|---|---|---|---|---|"]
    for level in ("L0", "L2", "L3"):
        base = load(f"{level}_E0")
        for r in (480, 640, 800, 960):
            cache = f"{level}_E0" if r == 640 else f"{level}_E0-r{r}"
            s = load(cache)
            summ = summarize(s)
            d = diff(base, s) if r != 640 else None
            vs_e = diff(load(f"{level}_{best_enh[level][0]}"), s) if level in best_enh else None
            out.append(f"| {level} | {r} | {pct(summ['auc'])} [{pct(summ['ci'][0])}, {pct(summ['ci'][1])}] | "
                       f"{fmt_diff(d) if d else '—'} | {fmt_diff(vs_e) + ' (vs ' + best_enh[level][0] + ')' if vs_e else '—'} | "
                       f"`{ids.get((cache, 0.25), '?')[:8]}` |")
    out.append("")

    out += ["## T5. Mechanism control — darkness vs noise at α = 0.1", "",
            "| Comparison | Δ AUC |", "|---|---|",
            f"| L2-nonoise E0 − L0 E0 (darkness only) | {fmt_diff(diff(load('L0_E0'), load('L2-nonoise_E0')))} |",
            f"| L2 E0 − L2-nonoise E0 (adding sensor noise) | {fmt_diff(diff(load('L2-nonoise_E0'), load('L2_E0')))} |", ""]
    args.out.write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
