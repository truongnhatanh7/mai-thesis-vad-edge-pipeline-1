def f(x, nd=2, sign=False):
    if x is None or (isinstance(x, float) and (math.isnan(x))):
        return "n/a"
    if isinstance(x, float) and math.isinf(x):
        return "inf"
    return f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"


def ci(c, nd=2):
    return "n/a" if not c else f"[{c[0]:+.{nd}f}, {c[1]:+.{nd}f}]"


def star(c) -> str:
    return "\\*" if c and (c["ci95"][0] > 0 or c["ci95"][1] < 0) else ""


def dci(c, nd=2) -> str:
    return f"{c['delta']:+.{nd}f} {ci(c['ci95'], nd)}{star(c)}"


def table(header: list[str], rows: list[list], align: str | None = None) -> str:
    align = align or ("|:--" + "|--:" * (len(header) - 1) + "|")
    out = ["| " + " | ".join(header) + " |", align]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def yn(b) -> str:
    return "yes" if b else "**NO**"


