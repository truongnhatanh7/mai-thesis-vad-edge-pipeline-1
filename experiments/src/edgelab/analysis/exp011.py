"""EXP-011: recall of the edge detector by person height (plan frozen 2026-11-07 18:30).

    uv run --extra pose python -m edgelab.analysis.exp011 [--out-dir <dir>]      # single-threaded, a few minutes

Reference people = released AlphaPose test poses (ShanghaiTech); a reference box = min/max of its keypoints with conf > 0 (height = y2 - y1).
A reference person is "found" when a cached YOLO box with conf >= 0.25 on the same frame has IoU >= 0.3 with that box (the EXP-009 D1 matcher).
"""

import argparse
import json
from pathlib import Path

import numpy as np

from edgelab.analysis.exp009 import RELEASED_POSE_DIR, detector_boxes, iou_with_boxes, keypoint_box
from edgelab.pose.fill import SUFFIX, merge_parts

DATA = Path.home() / "thesis-data"
EXPERIMENT_DIR = Path(__file__).resolve().parents[3] / "EXP-011-recall-by-height"
BIN_EDGES = [0, 32, 48, 64, 96, 160, np.inf]  # px; bin i = [edge i, edge i+1)
BIN_NAMES = ["<32", "32-48", "48-64", "64-96", "96-160", ">=160"]
CACHES = ["L0_E0-r480", "L0_E0", "L0_E0-r800", "L0_E0-r960", "L2_E0", "L3_E0"]  # 640 = L0_E0
CONF, IOU_MIN = 0.25, 0.3


def height_bin(height: float) -> int:
    return int(np.searchsorted(BIN_EDGES, height, side="right") - 1)


def reference_people(pose_dir: Path = RELEASED_POSE_DIR) -> dict[str, list[tuple[int, float, np.ndarray]]]:
    """video -> [(frame, height, box)] for every released pose that has a keypoint box."""
    people = {}
    for path in sorted(pose_dir.glob(f"*{SUFFIX}")):
        video = "_".join(path.name.split("_")[:2])
        out = []
        for track in json.loads(path.read_text()).values():
            for frame, pose in merge_parts(track).items():
                box = keypoint_box(np.asarray(pose["keypoints"], dtype=float).reshape(-1, 3))
                if box is not None:
                    out.append((int(frame), float(box[3] - box[1]), box))
        people[video] = out
    return people


def recall_by_bin(people: dict, cache: Path, conf: float = CONF, iou_min: float = IOU_MIN) -> dict:
    """-> {bin name: {"persons": n, "found": k}} plus "all"."""
    counts = np.zeros((len(BIN_NAMES), 2), dtype=np.int64)  # persons, found
    for video, entries in people.items():
        boxes = detector_boxes(cache / f"{video}.npz", conf)
        for frame, height, box in entries:
            b = height_bin(height)
            counts[b, 0] += 1
            found = boxes.get(frame)
            counts[b, 1] += int(found is not None and len(found) > 0 and (iou_with_boxes(box, found) >= iou_min).any())
    result = {name: {"persons": int(counts[i, 0]), "found": int(counts[i, 1])} for i, name in enumerate(BIN_NAMES)}
    result["all"] = {"persons": int(counts[:, 0].sum()), "found": int(counts[:, 1].sum())}
    return result


def recall(entry: dict) -> float:
    return entry["found"] / entry["persons"] if entry["persons"] else float("nan")


def wilson(entry: dict, z: float = 1.96) -> tuple[float, float]:
    n, k = entry["persons"], entry["found"]
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return float(centre - half), float(centre + half)


def pooled(result: dict, bins: list[str]) -> float:
    persons = sum(result[b]["persons"] for b in bins)
    return sum(result[b]["found"] for b in bins) / persons if persons else float("nan")


def verdicts(table: dict) -> dict:
    small48, large96 = ["<32", "32-48"], ["96-160", ">=160"]
    r640 = table["L0_E0"]
    r1 = {"recall_small_lt48": pooled(r640, small48), "recall_ge96": pooled(r640, large96)}
    r1["pass"] = bool(r1["recall_small_lt48"] <= 0.5 * r1["recall_ge96"])
    gain = {b: recall(table["L0_E0-r960"][b]) - recall(table["L0_E0"][b]) for b in BIN_NAMES}
    best = max(gain, key=lambda b: gain[b])
    r2 = {"absolute_gain_960_vs_640": gain, "largest_gain_bin": best, "pass": best in BIN_NAMES[:3]}
    drop = {b: (recall(table["L0_E0"][b]) - recall(table["L3_E0"][b])) / recall(table["L0_E0"][b])
            if recall(table["L0_E0"][b]) > 0 else float("nan") for b in BIN_NAMES}
    worst = max((b for b in BIN_NAMES if not np.isnan(drop[b])), key=lambda b: drop[b])
    r3 = {"relative_drop_L0_to_L3_at_640": drop, "largest_drop_bin": worst, "pass": worst in BIN_NAMES[:3]}
    return {"R1": r1, "R2": r2, "R3": r3}


def markdown(table: dict, v: dict) -> str:
    lines = ["# EXP-011 results: edge-detector recall by reference-person height (generated by `edgelab.analysis.exp011`)\n",
             "Reference people: released AlphaPose test poses (ShanghaiTech, 107 videos), box = min/max of keypoints with conf > 0, height = box height in px (856x480 frames).",
             "Found = a cached YOLOv8n-pose box with conf >= 0.25 and IoU >= 0.3 on the same frame (EXP-009 D1 matcher). Cells: recall (found / persons); Wilson 95% CI in the CSV-like block below.\n",
             "| cache | " + " | ".join(BIN_NAMES) + " | all |", "|---|" + "---|" * (len(BIN_NAMES) + 1)]
    for cache, res in table.items():
        cells = [f"{recall(res[b]):.3f} ({res[b]['found']}/{res[b]['persons']})" for b in BIN_NAMES + ["all"]]
        lines.append(f"| {cache} | " + " | ".join(cells) + " |")
    lines += ["\nCaches: `L0_E0-r480/L0_E0/-r800/-r960` = imgsz 480/640/800/960 at L0; `L2_E0`, `L3_E0` = 640 at darkness L2, L3.\n",
              "Wilson 95% CI of recall (low-high):\n", "| cache | " + " | ".join(BIN_NAMES) + " |", "|---|" + "---|" * len(BIN_NAMES)]
    for cache, res in table.items():
        lines.append(f"| {cache} | " + " | ".join("%.3f-%.3f" % wilson(res[b]) for b in BIN_NAMES) + " |")
    r1, r2, r3 = v["R1"], v["R2"], v["R3"]
    ok = lambda x: "PASS" if x["pass"] else "FAIL"  # noqa: E731
    fmt = lambda d: ", ".join(f"{k} {x:+.3f}" for k, x in d.items())  # noqa: E731
    lines += ["\n## Verdicts (plan §)\n", "| # | rule | numbers | verdict |", "|---|---|---|---|",
              f"| R1 | at 640 L0 recall(<48 px bins pooled) <= 0.5 x recall(>=96 px bins pooled) | {r1['recall_small_lt48']:.3f} vs {r1['recall_ge96']:.3f} (ratio {r1['recall_small_lt48'] / r1['recall_ge96']:.2f}) | {ok(r1)} |",
              f"| R2 | recall gain 960 vs 640 (absolute) largest in a <64 px bin | gains: {fmt(r2['absolute_gain_960_vs_640'])}; largest = {r2['largest_gain_bin']} | {ok(r2)} |",
              f"| R3 | relative recall drop L0 -> L3 at 640 largest in a <64 px bin | drops: {fmt(r3['relative_drop_L0_to_L3_at_640'])}; largest = {r3['largest_drop_bin']} | {ok(r3)} |",
              "\nInterpretation choices where the plan is silent: R1 pools the persons of the two bins on each side; R2 compares absolute recall gains (points of recall); R3 uses the relative drop as the plan says; bins with zero L0 recall would be skipped (none occurred if every bin has a number above)."]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=EXPERIMENT_DIR)
    args = parser.parse_args()
    people = reference_people()
    print("reference people:", sum(len(x) for x in people.values()), flush=True)
    table = {}
    for cache in CACHES:
        table[cache] = recall_by_bin(people, DATA / "exp003/cache" / cache)
        print(cache, json.dumps(table[cache]["all"]), flush=True)
    v = verdicts(table)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "recall_by_height.json").write_text(json.dumps({"table": table, "verdicts": v}, indent=1, default=str))
    (args.out_dir / "results.md").write_text(markdown(table, v))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(7, 4))
        for cache, res in table.items():
            ax.plot(BIN_NAMES, [recall(res[b]) for b in BIN_NAMES], marker="o", label=cache)
        ax.set_xlabel("reference person height (px)")
        ax.set_ylabel("edge recall (IoU >= 0.3, conf >= 0.25)")
        ax.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(args.out_dir / "recall_by_height.png", dpi=120)
    except Exception as error:  # the plot is optional
        print("no plot:", error)


if __name__ == "__main__":
    main()
