"""EXP-010b: EXP-010 with keep-mask seed 2 (plan frozen 2026-11-07 18:30). Same code as exp010, other seed and output root.

    uv run --extra pose python -m edgelab.analysis.exp010b run --part SHT      # or UB
    uv run --extra pose python -m edgelab.analysis.exp010b analyse             # S1 / S2 -> ~/thesis-data/exp010b/verdicts.json, results.md
"""

import argparse
import json
import os
from pathlib import Path

from edgelab.analysis import exp010
from edgelab.analysis.exp010 import DATA, GROUPS, PARTS, SLOWDOWNS, paired, read_rows, run_part
from edgelab.pose.score_dir import VARIANTS

SEED = 2
OUT_ROOT = DATA / "exp010b"
EXPERIMENT_DIR = Path(__file__).resolve().parents[3] / "EXP-010b-seed2"
MIN_WINDOWS = 200  # S2: a cell counts only if both arms have at least this many scorable windows


def configure():
    exp010.configure(SEED, OUT_ROOT, "EXP-010b", EXPERIMENT_DIR)


def is_degenerate(skip_row: dict, fill_row: dict) -> bool:
    return min(skip_row["num_segments"], fill_row["num_segments"]) < MIN_WINDOWS


def analyse() -> dict:
    configure()
    rows = read_rows()
    by = {(r["condition"], r["variant"]): r for r in rows}
    table, degenerate = {}, {}
    for group in GROUPS:
        for s in SLOWDOWNS:
            skip, fill = by[(f"{group}/s{s}/SKIP", "live")], by[(f"{group}/s{s}/FILL-HOLD", "live")]
            degenerate[f"{group}/s{s}"] = is_degenerate(skip, fill)
            for variant in VARIANTS:
                table[f"{group}/s{s}/{variant}"] = {**paired(group, s, "FILL-HOLD", variant, by),
                                                    "windows_skip": by[(f"{group}/s{s}/SKIP", variant)]["num_segments"],
                                                    "windows_fill": by[(f"{group}/s{s}/FILL-HOLD", variant)]["num_segments"]}
    significant = lambda key: table[key]["diff"] > 0 and table[key]["ci"][0] > 0  # noqa: E731
    verdicts = {"table": table, "degenerate_cells": [k for k, v in degenerate.items() if v], "seed": SEED}
    wins_s1 = [g for g in GROUPS if significant(f"{g}/s3/live") and not degenerate[f"{g}/s3"]]
    wins_s2 = [g for g in GROUPS if significant(f"{g}/s6/live") and not degenerate[f"{g}/s6"]]
    verdicts["S1"] = {"groups_significant": wins_s1, "n": len(wins_s1), "pass": len(wins_s1) >= 4}
    verdicts["S2"] = {"groups_significant_nondegenerate": wins_s2, "n": len(wins_s2), "pass": len(wins_s2) >= 4,
                      "significant_but_degenerate": [g for g in GROUPS if significant(f"{g}/s6/live") and degenerate[f"{g}/s6"]]}
    (OUT_ROOT / "verdicts.json").write_text(json.dumps(verdicts, indent=1))
    (EXPERIMENT_DIR / "results_tables.md").write_text(markdown(rows, verdicts))
    print(json.dumps({k: v for k, v in verdicts.items() if k != "table"}, indent=1))
    return verdicts


def markdown(rows: list[dict], verdicts: dict) -> str:
    table, ok = verdicts["table"], lambda x: "PASS" if x["pass"] else "FAIL"  # noqa: E731
    s1, s2 = verdicts["S1"], verdicts["S2"]
    lines = ["# EXP-010b results (seed 2; generated by `edgelab.analysis.exp010b analyse`; AUC x 100, paired bootstrap over videos, 1000 resamples)\n",
             "## Verdicts\n", "| # | rule (live) | result | verdict |", "|---|---|---|---|",
             f"| S1 | FILL-HOLD - SKIP > 0, CI excludes 0, >= 4 of 6 groups at s = 3 | {s1['n']} of 6 ({', '.join(s1['groups_significant']) or 'none'}) | {ok(s1)} |",
             f"| S2 | same at s = 6, only cells with >= {MIN_WINDOWS} windows in both arms | {s2['n']} of 6 ({', '.join(s2['groups_significant_nondegenerate']) or 'none'}) | {ok(s2)} |",
             f"\nDegenerate cells (< {MIN_WINDOWS} scorable windows in at least one arm): {', '.join(verdicts['degenerate_cells']) or 'none'}. "
             f"Significant-but-degenerate (not counted): {', '.join(s2['significant_but_degenerate']) or 'none'}.\n",
             "## FILL-HOLD - SKIP (positive = fill better)\n",
             "| group | s | drop rate | windows SKIP / FILL | SKIP live | fill live | diff live [95% CI] | SKIP paper | fill paper | diff paper [95% CI] | degenerate |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for group in GROUPS:
        for s in SLOWDOWNS:
            lv, pp = table[f"{group}/s{s}/live"], table[f"{group}/s{s}/paper"]
            row = next(x for x in rows if x["condition"] == f"{group}/s{s}/FILL-HOLD" and x["variant"] == "live")
            star = lambda t: "*" if t["ci"][0] > 0 or t["ci"][1] < 0 else ""  # noqa: E731
            lines.append(f"| {group} | {s} | {row['drop_rate']:.2f} | {lv['windows_skip']} / {lv['windows_fill']} | {lv['skip']:.2f} | {lv['policy']:.2f} | "
                         f"{lv['diff']:+.2f} [{lv['ci'][0]:+.2f}, {lv['ci'][1]:+.2f}]{star(lv)} | {pp['skip']:.2f} | {pp['policy']:.2f} | "
                         f"{pp['diff']:+.2f} [{pp['ci'][0]:+.2f}, {pp['ci'][1]:+.2f}]{star(pp)} | "
                         f"{'yes' if f'{group}/s{s}' in verdicts['degenerate_cells'] else ''} |")
    lines += ["\n(* = 95% CI excludes 0)\n", "## All arms (AUC [95% CI over videos])\n", "| condition | paper | live | windows |", "|---|---|---|---|"]
    for cond in dict.fromkeys(x["condition"] for x in rows):
        paper = next(x for x in rows if x["condition"] == cond and x["variant"] == "paper")
        live = next(x for x in rows if x["condition"] == cond and x["variant"] == "live")
        fmt = lambda x: f"{x['auc'] * 100:.2f}" + (f" [{x['ci'][0] * 100:.1f}, {x['ci'][1] * 100:.1f}]" if x["ci"] else "")  # noqa: E731
        lines.append(f"| {cond} | {fmt(paper)} | {fmt(live)} | {paper['num_segments']} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("run")
    run.add_argument("--part", choices=list(PARTS), required=True)
    run.add_argument("--threads", type=int, default=2)
    sub.add_parser("analyse")
    args = parser.parse_args()
    os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
    if args.command == "run":
        configure()
        run_part(args.part, args.threads)
    else:
        analyse()


if __name__ == "__main__":
    main()
